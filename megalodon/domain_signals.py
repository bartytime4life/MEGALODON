"""Review-only spelling signals for observed hostnames. No lookup, verdict or action.

A signal describes how a name is written, not who owns it or whether it is
safe. Cloud, CDN and tracking hostnames are routinely machine-generated, so a
signal is a reason to look, never evidence of malware or a generated (DGA)
domain on its own. Thresholds are code, never values from a reference update.
"""
from collections import Counter
import math
import re

SCHEMA = 'megalodon-name-review-v1'
MAX_NAMES = 5
MAX_SNAPSHOT_RECORDS = 64
MAX_LABEL_SHOWN = 32
MAX_NAME_CHARS = 253
ENTROPY_MIN_CHARS = 12
HIGH_ENTROPY_BITS = 3.5
LONG_LABEL_CHARS = 24
CONSONANT_RUN = 6
DEEP_LABELS = 6
DEEP_CHARS = 100
HEX_LABEL_CHARS = 16
ENCODED_LABELS = 3
ENCODED_LABEL_CHARS = 10
ATTACK = ('T1568.002', 'T1071.004')
_NAME = re.compile(r'[a-z0-9][a-z0-9._-]{0,252}')
_CONSONANTS = re.compile(r'[bcdfghjklmnpqrstvwxz]{%d,}' % CONSONANT_RUN)
_HEX = re.compile(r'[0-9a-f]{%d,}' % HEX_LABEL_CHARS)
# Providers whose hostnames are generated by design. Matching one caps the
# level at a note; it does not establish that the endpoint is safe.
GENERATED_SUFFIXES = ('cloudfront.net', 'amazonaws.com', 'akamaiedge.net', 'akamaitechnologies.com',
                      'edgekey.net', 'azureedge.net', 'cloudapp.azure.com', 'fastly.net',
                      'googlevideo.com', 'googleusercontent.com', '1e100.net', 'in-addr.arpa', 'ip6.arpa')


def _shown(label):
    """Keep detail text bounded; the full name is carried once in the record."""
    return label if len(label) <= MAX_LABEL_SHOWN else label[:MAX_LABEL_SHOWN]+'...'


def entropy(label):
    """Shannon entropy in bits per character."""
    total = len(label)
    return -sum(n/total*math.log2(n/total) for n in Counter(label).values()) if total else 0.0


def assess(name):
    """Return one bounded review record for a hostname, or None without signals."""
    if type(name) is not str or len(name) > MAX_NAME_CHARS:
        return None
    name = name.lower().rstrip('.')
    if not _NAME.fullmatch(name) or '..' in name:
        return None
    labels = name.split('.')
    suffix = next((s for s in GENERATED_SUFFIXES if name == s or name.endswith('.'+s)), None)
    # The top-level label and a known generated suffix describe the provider, not the host.
    own = labels[:-(suffix.count('.')+1)] if suffix else labels[:-1] if len(labels) > 1 else labels
    signals = {}
    for label in own:
        if label.startswith('xn--'):
            signals.setdefault('punycode', f'"{_shown(label)}" is an internationalized (punycode) label; check for look-alike spelling.')
            continue
        shown = _shown(label)
        letters = sum(c.isalpha() for c in label)
        digits = sum(c.isdigit() for c in label)
        # Hyphenated words are long but not random; measure the longest segment.
        segment = max(re.split(r'[-_]', label), key=len)
        if len(segment) >= ENTROPY_MIN_CHARS and entropy(segment) >= HIGH_ENTROPY_BITS:
            signals.setdefault('high_entropy', f'"{shown}" uses unusually varied characters ({entropy(segment):.1f} bits each), as random names do.')
        if len(label) >= LONG_LABEL_CHARS:
            signals.setdefault('long_label', f'"{shown}" is {len(label)} characters long.')
        if len(label) >= 8 and letters and 0.3 <= digits/len(label) <= 0.9:
            signals.setdefault('digit_mix', f'"{shown}" mixes letters and digits throughout.')
        if _CONSONANTS.search(label):
            signals.setdefault('consonant_run', f'"{shown}" has a run of {CONSONANT_RUN} or more consonants, which is rare in words.')
        if _HEX.fullmatch(label) and letters and digits:
            signals.setdefault('hex_label', f'"{shown}" looks like a hexadecimal string.')
    if sum(len(label) >= ENCODED_LABEL_CHARS for label in own) >= ENCODED_LABELS:
        signals['stacked_labels'] = f'{ENCODED_LABELS} or more labels are at least {ENCODED_LABEL_CHARS} characters long, as encoded data often is.'
    if len(labels) >= DEEP_LABELS or len(name) >= DEEP_CHARS:
        signals['deep_name'] = f'The name has {len(labels)} labels and {len(name)} characters; long names can carry encoded data.'
    if not signals:
        return None
    level = 'review' if len(signals) >= 2 and suffix is None else 'note'
    context = ['A spelling signal is not evidence of malware, a generated domain or intent.']
    if suffix:
        context.insert(0, f'Providers commonly generate names under {suffix}; this spelling is expected there. That does not establish safety.')
    return dict(schema=SCHEMA, name=name, level=level, attack=list(ATTACK),
                signals=[dict(id=key, detail=detail) for key, detail in signals.items()],
                context=context, action_status='not_attempted')


def review(names):
    """Assess up to MAX_NAMES distinct observed names; never resolves or contacts them."""
    results, seen = [], set()
    for row in names if isinstance(names, list) else []:
        value = row.get('name') if isinstance(row, dict) else None
        if type(value) is not str or value.lower() in seen:
            continue
        seen.add(value.lower())
        result = assess(value)
        if result is not None:
            results.append(result)
        if len(seen) >= MAX_NAMES:
            break
    return sorted(results, key=lambda r: (r['level'] != 'review', r['name']))
